counter <- 0L
run <- function(code, parent = "", success = TRUE) {
  counter <<- counter + 1L
  work <- file.path(engine, paste0("job-", counter)); dir.create(work)
  jsonlite::write_json(list(action = "legacy", checkpoint = parent, code = code, project = project, progressToken = paste0("test-", counter)), file.path(work, "request.json"), auto_unbox = TRUE)
  status <- system2(file.path(R.home("bin"), "Rscript"), c("--vanilla", shQuote(file.path(engine, "runner.R")), "legacy", shQuote(engine), shQuote(work), shQuote(lib)), stdout = file.path(work, "run.log"), stderr = file.path(work, "run.log"))
  if (success && status != 0) stop(paste(readLines(file.path(work, "run.log")), collapse = "\n"))
  if (!success && status == 0) stop("Expected failure")
  list(work = work, checkpoint = file.path(work, "workspace.rds"), result = if (status == 0) jsonlite::read_json(file.path(work, "result.json"), simplifyVector = TRUE) else NULL)
}
