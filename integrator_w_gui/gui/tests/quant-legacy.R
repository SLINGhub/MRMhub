progress_records <- function(work) {
  lines <- readLines(file.path(work, "run.log"), warn = FALSE)
  prefix <- "__MRMHUB_QUANT_PROGRESS__"
  lapply(substring(lines[startsWith(lines, prefix)], nchar(prefix) + 1L), jsonlite::fromJSON)
}
